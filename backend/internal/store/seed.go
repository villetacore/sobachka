package store

import "context"

// Ключевые слова ищутся как НАЧАЛО слова: «сайт» найдёт «сайта», «сайтов».
// Слова до 3 букв («cms», «seo») — только целиком. Фразы — слова подряд: «интернет магазин».
//
// В базе создаётся один профиль-пример: он показывает, как заполнять профиль. Переименуйте его
// под своё направление или удалите и создайте свои в разделе «Профили».
var seedProfiles = []Profile{
	{
		Name:        "Пример: разработка сайтов",
		Description: "Пример профиля. Замените название, ключевые слова и шаблон отклика на свои.",
		Keywords: []string{"сайт", "лендинг", "landing", "интернет магазин", "верстк", "wordpress", "tilda", "битрикс",
			"frontend", "react", "vue", "html", "css"},
		MinusWords: []string{"наполнени", "копирайт"},
		PitchNotes: "Делаю сайты под ключ: от прототипа и вёрстки до запуска и поддержки.",
		PitchTemplate: "Здравствуйте! Возьмусь за «{title}» — это моё направление ({matched}).\n\n" +
			"{experience}\n\n" +
			"Подскажите, есть ли техническое задание или примеры сайтов, которые вам нравятся? После этого назову сроки и стоимость.\n" +
			"---\n" +
			"Здравствуйте! По задаче «{title}» могу предложить решение под ключ.\n\n" +
			"{experience}\n\n" +
			"Пришлите, пожалуйста, детали задачи — оценю объём работ в течение дня.",
	},
}

// Дефис и пробел в ключах равнозначны: «интернет магазин» найдёт и «интернет-магазин».
// «Учебные» заказы чаще всего не нужны — уберите из минус-слов, если берёте такие.
var seedMinusWords = []string{"курсов", "дипломн", "реферат", "контрольн работ"}

// Seed создаёт профиль-пример в пустой базе. Источников по умолчанию нет: площадки
// добавляются в интерфейсе (или из файла готовых площадок, см. PRESETS_FILE).
func (s *Store) Seed(ctx context.Context) error {
	var n int
	if err := s.db.QueryRow(ctx, `SELECT count(*) FROM profiles`).Scan(&n); err != nil {
		return err
	}
	if n == 0 {
		for _, p := range seedProfiles {
			p.Enabled = true
			// Порог 0.6: одно слово в заголовке (0.80) или два в описании (0.80) — да, одно в описании (0.55) — нет.
			p.Threshold = 0.6
			p.MinusWords = append(append([]string{}, p.MinusWords...), seedMinusWords...)
			if _, err := s.CreateProfile(ctx, p); err != nil {
				return err
			}
		}
	}
	return nil
}

// SeedProfiles возвращает копию стартовых профилей (для тестов шаблонов).
func SeedProfiles() []Profile {
	return append([]Profile(nil), seedProfiles...)
}
